"""Tier-1 export: package the 5-seed synthetic runs of agent-watch and rogue-ai-pipeline.

TWO input paths, both tolerant of the other worker's in-progress changes:

1. EXISTING EVAL OUTPUTS (cheap, always tried): ``docs/eval-*.json`` (agent-watch) and ``sample_outputs/{evaluation,web_evaluation}.json``
   (pipeline), plus any ``--eval-json`` you pass.  Read as plain JSON, scrubbed, embedded verbatim; nothing about their internals is assumed.
   The heavyweight eval scripts (scripts/eval_v3.py, scripts/eval_web.py) need a v2/v3 source tree and per-version subprocesses, so
   they are NOT run here; regenerate their JSON with them and pass it via ``--eval-json``.
2. FRESH GENERATION (``generate=True``): the generators themselves, seeds 0-4, in-process, no network:
   * pipeline: ``rogue_pipeline.simulator.build`` + ``web_simulator.build_web`` -> ground-truth label records + event count/sha256 per seed
   * agent-watch: ``agentwatch.synthetic.generate_demo`` -> truth records + log sha256 per seed (needs Flask: the honeypot app is driven via
     its test client; if Flask or anything else is unavailable that source is reported as 'skipped' with the exception class, not faked)

Honesty: all of it is written by the same author as the detectors it exercises.  Every record and file carries ``same_author_synthetic: true``.
"""
from __future__ import annotations

import contextlib
import importlib
import json
import sys
import tempfile
from pathlib import Path
from typing import Any, Optional

from .. import TIER1
from ..common import file_entry, sha256_file, sha256_json, write_json, write_jsonl
from ..secrets_guard import BundleScrubber

SAME_AUTHOR_NOTE = ("SAME-AUTHOR SYNTHETIC DATA: generated by the same author who wrote the detectors it is used to test. "
                    "A regression check (did a change break something we already handle?), NOT evidence of real-world detection.")
RECORD_SCHEMA = "agentwatch.bench.tier1.record/1"
DEFAULT_SEEDS = (0, 1, 2, 3, 4)
PIPELINE_ASSISTANTS = 40


def stamp(rec: dict[str, Any]) -> dict[str, Any]:
    return {"schema": RECORD_SCHEMA, "tier": TIER1, "same_author_synthetic": True, **rec}


def headline(obj: Any, depth: int = 3, max_keys: int = 60) -> Any:
    """Scalar-only projection of a nested eval JSON (lists dropped, depth/keys capped) for the manifest.  Numbers are copied, never combined."""
    if isinstance(obj, dict):
        if depth == 0:
            return None
        out = {}
        for k, v in list(obj.items())[:max_keys]:
            if isinstance(v, (int, float, str, bool)) or v is None:
                out[str(k)] = v if not isinstance(v, str) else v[:120]
            elif isinstance(v, dict):
                h = headline(v, depth - 1, max_keys)
                if h:
                    out[str(k)] = h
        return out
    return None


def _eval_sources(aw_root: Path, pipe_root: Path, extra: list[Path]) -> list[tuple[str, str, Path]]:
    found: list[tuple[str, str, Path]] = []
    for p in sorted((aw_root / "docs").glob("eval-*.json")):
        found.append(("agent-watch", f"agent-watch/docs/{p.name}", p))
    for name in ("evaluation.json", "web_evaluation.json"):
        p = pipe_root / "sample_outputs" / name
        if p.is_file():
            found.append(("rogue-ai-pipeline", f"rogue-ai-pipeline/sample_outputs/{name}", p))
    for p in extra:
        found.append(("user_supplied", f"user_supplied/{p.name}", p))
    return found


def _declared_seeds(obj: Any) -> Optional[list]:
    if isinstance(obj, dict):
        if isinstance(obj.get("seeds"), list):
            return obj["seeds"]
        for v in obj.get("levels", {}).values() if isinstance(obj.get("levels"), dict) else []:
            if isinstance(v, dict) and isinstance(v.get("seeds"), list):
                return v["seeds"]
    return None


@contextlib.contextmanager
def _on_path(root: Path):
    sys.path.insert(0, str(root))
    try:
        yield
    finally:
        with contextlib.suppress(ValueError):
            sys.path.remove(str(root))


def _gen_pipeline(pipe_root: Path, seeds: tuple[int, ...]) -> tuple[list[dict], dict]:
    with _on_path(pipe_root):
        sim = importlib.import_module("rogue_pipeline.simulator")
        web = importlib.import_module("rogue_pipeline.web_simulator")
        recs: list[dict] = []
        per_seed: dict[str, Any] = {}
        for seed in seeds:
            base = sim.build(seed, PIPELINE_ASSISTANTS, extended=True)
            w = web.build_web(seed, v4=True)
            n_lab = 0
            for src, data in (("rogue-ai-pipeline/simulator", base), ("rogue-ai-pipeline/web_simulator", w)):
                for agent, (kind, group) in sorted(data.labels.items()):
                    recs.append(stamp({"source": src, "kind": "ground_truth_label", "seed": seed, "agent": agent, "label": kind, "group": group}))
                    n_lab += 1
            per_seed[str(seed)] = {"labels": n_lab, "base_events": len(base.events), "web_events": len(w.events),
                                   "events_sha256": sha256_json([base.events, w.events])}
        return recs, per_seed


def _gen_agentwatch(aw_root: Path, seeds: tuple[int, ...]) -> tuple[list[dict], dict]:
    with _on_path(aw_root):
        syn = importlib.import_module("agentwatch.synthetic")
        recs: list[dict] = []
        per_seed: dict[str, Any] = {}
        for seed in seeds:
            with tempfile.TemporaryDirectory(prefix="aw-bench-t1-") as td:
                art = syn.generate_demo(Path(td), seed=seed, extended=True)
                for t in art["truth"]:
                    recs.append(stamp({"source": "agent-watch/synthetic", "kind": "ground_truth_label", "seed": seed,
                                       "agent": t.name, "label": t.label, "group": t.note or t.label, "benign": bool(t.benign)}))
                lines = {k: sum(1 for _ in open(art[k], "rb")) if Path(art[k]).exists() else 0 for k in ("access_log", "gateway_log", "leads", "access_mirror")}
                per_seed[str(seed)] = {"truth_entries": len(art["truth"]), "line_counts": lines,
                                       "access_log_sha256": sha256_file(Path(art["access_log"])),
                                       "gateway_log_sha256": sha256_file(Path(art["gateway_log"]))}
        return recs, per_seed


def export_tier1(out_root: Path, *, aw_root: Path, pipe_root: Path, seeds: tuple[int, ...] = DEFAULT_SEEDS, generate: bool = True,
                 eval_jsons: Optional[list[Path]] = None, scrubber: Optional[BundleScrubber] = None,
                 inject: Optional[dict[str, Any]] = None) -> dict[str, Any]:
    """Write ``out_root/tier1_synthetic_regression/``; returns the tier's manifest block (status, sources, files, metrics).

    ``inject`` (tests): ``{"agentwatch": callable, "pipeline": callable}`` replacing the generators with fixtures returning (records, per_seed).
    """
    scrubber = scrubber or BundleScrubber()
    tier_dir = out_root / TIER1
    tier_dir.mkdir(parents=True, exist_ok=True)
    sources: dict[str, Any] = {}
    metrics: dict[str, Any] = {}
    records: list[dict] = []
    # 1. existing eval outputs
    for system, label, path in _eval_sources(aw_root, pipe_root, list(eval_jsons or [])):
        try:
            obj = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            sources[label] = {"status": "skipped", "reason": "unreadable or not JSON"}
            continue
        clean = scrubber.scrub(obj)
        seeds_declared = _declared_seeds(clean)
        fname = "eval_" + label.replace("/", "__")
        write_json(tier_dir / "eval_outputs" / fname, {"same_author_synthetic": True, "note": SAME_AUTHOR_NOTE, "origin": label,
                                                       "origin_sha256": sha256_file(path), "content": clean})
        sources[label] = {"status": "consumed_existing_output", "seeds_declared": seeds_declared, "same_author_synthetic": True,
                          "file": f"eval_outputs/{fname}",
                          **({} if seeds_declared else {"seeds_note": "file does not declare its seeds; treat as a single fixed-seed run (eval_v3.py defaults to seed 7), NOT 5-seed data"})}
        metrics[label] = {"same_author_synthetic": True, "seeds_declared": seeds_declared, "headline_scalars": headline(clean),
                          "full_file": f"eval_outputs/{fname}"}
    # 2. fresh generation
    gens = {"rogue-ai-pipeline": (inject or {}).get("pipeline") or (lambda: _gen_pipeline(pipe_root, seeds)),
            "agent-watch": (inject or {}).get("agentwatch") or (lambda: _gen_agentwatch(aw_root, seeds))}
    for name, fn in gens.items():
        label = f"generated/{name}"
        if not generate:
            sources[label] = {"status": "skipped", "reason": "generation disabled (--no-generate)"}
            continue
        try:
            recs, per_seed = fn()
        except Exception as exc:                      # missing dependency / interface changed mid-flight: report, never fake
            sources[label] = {"status": "skipped", "reason": f"{type(exc).__name__}: generator unavailable (see docs/benchmark-protocol.md)"}
            continue
        records += recs
        sources[label] = {"status": "generated", "seeds": sorted(int(s) for s in per_seed), "same_author_synthetic": True,
                          "n_records": len(recs)}
        metrics[label] = {"same_author_synthetic": True, "per_seed_counts": per_seed,
                          "note": "counts and hashes of generator output; no detector score is computed here"}
    records = [stamp({k: v for k, v in r.items() if k not in ("schema", "tier", "same_author_synthetic")}) for r in scrubber.scrub(records)]
    assert all(r["same_author_synthetic"] is True for r in records)
    write_jsonl(tier_dir / "records.jsonl", records)
    write_json(tier_dir / "metrics.json", {"same_author_synthetic": True, "note": SAME_AUTHOR_NOTE, "metrics": metrics, "sources": sources})
    (tier_dir / "README.md").write_text(
        f"# Tier 1 - synthetic regression\n\n**{SAME_AUTHOR_NOTE}**\n\n- `records.jsonl`: ground-truth label records, every one stamped "
        f"`\"same_author_synthetic\": true`.\n- `eval_outputs/`: existing eval JSON, scrubbed, embedded verbatim and stamped.\n- `metrics.json`: per-source metrics "
        f"(never combined across sources or with other tiers).\n\nSeeds are listed per source; an eval output that declares fewer than 5 seeds "
        f"(e.g. eval_v3.py defaults to one) is not 5-seed data.\n", encoding="utf-8")
    files = [file_entry(out_root, p) for p in sorted(tier_dir.rglob("*")) if p.is_file()]
    return {"status": "populated" if (records or metrics) else "empty", "same_author_synthetic": True, "n_records": len(records),
            "sources": sources, "metrics": {k: {"headline_scalars": v.get("headline_scalars"), "per_seed_counts": v.get("per_seed_counts"),
                                               "seeds_declared": v.get("seeds_declared")} for k, v in metrics.items()},
            "files": files}
