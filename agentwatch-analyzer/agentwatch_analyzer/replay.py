"""CSP-safe static HTML session replay for offline findings (no network, secrets scrubbed)."""
from __future__ import annotations

import html
from typing import Any, Iterable

from .parse import Event
from .scrub import scrub_text

CSP = "default-src 'none'; style-src 'unsafe-inline'; img-src 'none'; connect-src 'none'; form-action 'none'"

_CSS = """
body{font:14px/1.45 system-ui,sans-serif;margin:0;background:#f5f6f8;color:#1b1f24}
header{background:#1b1f24;color:#fff;padding:14px 20px}header h1{margin:0;font-size:18px}
header p{margin:4px 0 0;color:#c9d1d9;font-size:12px}
main{padding:14px 20px;max-width:1100px;margin:auto}
section{background:#fff;border:1px solid #d0d7de;border-radius:8px;margin:12px 0;padding:12px 14px}
table{border-collapse:collapse;width:100%;font-size:12px}th,td{border-bottom:1px solid #eee;padding:4px 6px;text-align:left;vertical-align:top}
.badge{display:inline-block;background:#fff8c5;border:1px solid #d4a72c;border-radius:4px;padding:1px 6px;font-size:11px}
.rule{color:#cf222e;font-weight:600}
"""


def _e(s: Any) -> str:
    return html.escape(scrub_text(str(s), drop_query=True), quote=True)


def build_replay_html(
    by_key: dict[str, list[Event]],
    findings: list[dict[str, Any]],
    *,
    title: str = "agentwatch-analyzer offline replay",
) -> str:
    findings_by = {}
    for f in findings:
        findings_by.setdefault(f.get("session_key", ""), []).append(f)
    parts = [
        "<!DOCTYPE html><html lang='en'><head><meta charset='utf-8'>",
        f"<meta http-equiv=\"Content-Security-Policy\" content=\"{CSP}\">",
        f"<title>{_e(title)}</title><style>{_CSS}</style></head><body>",
        "<header><h1>Offline session replay</h1>",
        "<p>Static analysis only — no honeypot, no network, secrets scrubbed. For human review; not a verdict.</p></header><main>",
        "<p class='badge'>UNTRUSTED LOG INPUT — SCRUBBED</p>",
    ]
    for key, evs in list(by_key.items())[:60]:
        fs = findings_by.get(key, [])
        rules = ", ".join(sorted({f.get("rule_id", "?") for f in fs})) or "none"
        parts.append(f"<section><h2>{_e(key)}</h2>")
        parts.append(f"<p>Findings: <span class='rule'>{_e(rules)}</span> ({len(fs)})</p>")
        if fs:
            parts.append("<ul>")
            for f in fs[:12]:
                parts.append(f"<li><strong>{_e(f.get('rule_id'))}</strong> — {_e(f.get('summary', ''))}</li>")
            parts.append("</ul>")
        parts.append("<table><thead><tr><th>ts</th><th>method</th><th>path</th><th>status</th><th>referer</th></tr></thead><tbody>")
        for e in sorted(evs, key=lambda x: x.ts)[:400]:
            parts.append(
                f"<tr><td>{_e(e.ts)}</td><td>{_e(e.method)}</td><td>{_e(e.path)}</td>"
                f"<td>{_e(e.status)}</td><td>{_e(e.referer)}</td></tr>"
            )
        parts.append("</tbody></table></section>")
    parts.append("<p style='font-size:12px;color:#57606a'>Generated by agentwatch-analyzer. Beacon/VLM/R11–R13 signals are N/A offline.</p>")
    parts.append("</main></body></html>")
    return "".join(parts)
