"""Build 'sample flagged cases' from an analysis: a readable evidence package per alert."""
from __future__ import annotations

import datetime as _dt
import re
from typing import Dict, List

from .alerts import Alert
from .features import SENSITIVE
from .pipeline import Analysis
from .schema import Event


_BLOB = re.compile(r"[A-Za-z0-9+/=]{24,}")


def _iso(t: float) -> str:
    return _dt.datetime.fromtimestamp(t, tz=_dt.timezone.utc).strftime("%Y-%m-%d %H:%M:%SZ")


def case_for(al: Alert, an: Analysis, by_agent: Dict[str, List[Event]], roles: Dict[str, str] | None = None,
             n_events: int = 8) -> Dict:
    sample = {}
    for s in al.subjects[:3]:
        evs = by_agent.get(s, [])
        def score(e: Event) -> int:
            return (4 * e.dest_external + 3 * e.ingest_external + (not e.in_scope) + (e.status == "denied")
                    + 3 * bool(SENSITIVE.search(e.target)) + 3 * bool(_BLOB.search(e.text)))
        top = sorted(evs, key=lambda e: (-score(e), e.ts))[:n_events]
        pick = sorted(top, key=lambda e: e.ts) if top and score(top[0]) > 0 else evs[:n_events]
        sample[s] = [{"ts": _iso(e.ts), "kind": e.kind, "target": e.target, "status": e.status,
                      "text": (e.text[:60] + "...") if len(e.text) > 60 else e.text,
                      "dest_external": e.dest_external, "ingest_external": e.ingest_external} for e in pick]
    out = {"alert_id": al.alert_id, "severity": al.severity, "kind": al.kind, "subjects": al.subjects,
           "summary": al.summary, "last_evidence": _iso(al.ts), "atlas": al.atlas, "sample_events": sample,
           "synthetic": True}
    if roles:
        out["generator_ground_truth"] = {s: roles.get(s, "?") for s in al.subjects}
    return out


def render_markdown(cases: List[Dict], title: str = "Sample flagged cases") -> str:
    lines = [f"# {title}", "", "> SYNTHETIC DATA. Every agent, message and event below was generated by this project. "
             "Flags are behavioral leads for human review, not attributions.", ""]
    for c in cases:
        lines += [f"## {c['alert_id']}: {c['kind']} ({c['severity']})", "",
                  f"- Subjects: {', '.join(c['subjects'])}", f"- Last evidence: {c['last_evidence']}",
                  f"- Summary: {c['summary']}"]
        if c["atlas"]:
            lines.append("- MITRE ATLAS (approximate mapping): " + ", ".join(f"{a['id']} {a['name']}" for a in c["atlas"]))
        if "generator_ground_truth" in c:
            lines.append("- Generator ground truth (hidden from detectors): " +
                         ", ".join(f"{k}={v}" for k, v in c["generator_ground_truth"].items()))
        lines.append("- Example events:")
        for s, evs in c["sample_events"].items():
            for e in evs[:4]:
                extra = " [external dest]" if e["dest_external"] else (" [external ingest]" if e["ingest_external"] else "")
                lines.append(f"  - {s} {e['ts']} {e['kind']} -> {e['target']} ({e['status']}){extra} {e['text']}".rstrip())
        lines.append("")
    return "\n".join(lines)
