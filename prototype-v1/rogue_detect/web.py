def esc(x) -> str:
    return html.escape(str(x), quote=True)


def page(title: str, body: str) -> bytes:
    nav = ('<a href="/">Dashboard</a><a href="/report">Report suspicious activity</a>'
           '<a href="/resources">Developer resources</a><a href="/api/alerts">API: alerts</a>')
    return (f"<!doctype html><html lang=en><meta charset=utf-8><meta name=viewport content='width=device-width'>"
            f"<title>{esc(title)}</title><style>{CSS}</style><header><strong>Rogue AI Detection prototype</strong> "
            f"&nbsp; {nav}</header><main><div class=banner><strong>SYNTHETIC DATA ONLY.</strong> Every agent and event "
            f"shown here was generated by this project. Flags are leads for human review, not attributions.</div>"
            f"{body}</main></html>").encode()


def sev_badge(s: str) -> str:
    return f'<span class=sev style="background:{SEV_COLOR.get(s, "#777")}">{esc(s)}</span>'


def graph_svg(state: Dict, w: int = 760, h: int = 420) -> str:
    an = state["analysis"]
    sev_of: Dict[str, str] = {}
    rank = {"info": 0, "low": 1, "medium": 2, "high": 3}
    for al in an.alerts:
        for s in al.subjects:
            if rank[al.severity] >= rank.get(sev_of.get(s, "info"), 0):
                sev_of[s] = al.severity
    g = nx.Graph()
    for e in an.coord.edges:
        g.add_edge(e.a, e.b, ev="+".join(e.evidence()), multi=len(e.evidence()) >= 2)
    for a in sev_of:
        g.add_node(a)
    # keep the picture readable: drop nodes that are neither alerted nor in a multi-evidence edge
    keep = set(sev_of) | {n for e in an.coord.edges if len(e.evidence()) >= 2 for n in (e.a, e.b)}
    g = g.subgraph(keep).copy()
    if not g.nodes:
        return "<p>No coordination or alert subjects to draw.</p>"
    pos = nx.spring_layout(g, seed=3, k=0.9)
    xs = [p[0] for p in pos.values()]
    ys = [p[1] for p in pos.values()]
    def sx(v): return 40 + (v - min(xs)) / ((max(xs) - min(xs)) or 1) * (w - 80)
    def sy(v): return 30 + (v - min(ys)) / ((max(ys) - min(ys)) or 1) * (h - 60)
    out = [f'<svg viewBox="0 0 {w} {h}" width="100%" role="img" aria-label="coordination graph">']
    for a, b, d in g.edges(data=True):
        out.append(f'<line x1="{sx(pos[a][0]):.0f}" y1="{sy(pos[a][1]):.0f}" x2="{sx(pos[b][0]):.0f}" '
                   f'y2="{sy(pos[b][1]):.0f}" stroke="{"#b3261e" if d["multi"] else "#bbb"}" stroke-width="{2 if d["multi"] else 1}"/>')
    for n in g.nodes:
        c = SEV_COLOR.get(sev_of.get(n, ""), "#999")
        out.append(f'<circle cx="{sx(pos[n][0]):.0f}" cy="{sy(pos[n][1]):.0f}" r="9" fill="{c}"/>'
                   f'<text x="{sx(pos[n][0]) + 12:.0f}" y="{sy(pos[n][1]) + 4:.0f}" font-size="11">{esc(n)}</text>')
    out.append("</svg>")
    return "".join(out)


def render_dashboard(state: Dict) -> bytes:
    an = state["analysis"]
    roles = state.get("roles")
    rows = []
    for rec in state["log"].read():
        al = rec["alert"]
        tags = ", ".join(esc(t["id"]) for t in al["atlas"]) or "-"
        rows.append(f"<tr><td>{sev_badge(al['severity'])}</td><td>{esc(al['kind'])}</td>"
                    f"<td>{esc(', '.join(al['subjects']))}</td><td>{esc(al['summary'])}</td><td>{tags}</td></tr>")
    sev_counts: Dict[str, int] = {}
    for al in an.alerts:
        sev_counts[al.severity] = sev_counts.get(al.severity, 0) + 1
    body = [f"<h2>Overview</h2><p>{len(an.ids)} agents profiled. Alerts: "
            + ", ".join(f"{esc(k)} {v}" for k, v in sorted(sev_counts.items())) + ".</p>",
            f"<p>Alert log integrity: <strong>{'intact' if state['log'].verify() is None else 'BROKEN'}</strong> "
            f"(hash chain, {len(state['log'].read())} records).</p>",
            "<h2>Alert log</h2><table><tr><th>Severity</th><th>Kind</th><th>Agents</th><th>Why</th><th>ATLAS (approx.)</th></tr>"
            + "".join(rows) + "</table>",
            "<h2>Coordination graph</h2><p>Nodes are agents with alerts; red edges have two or more independent "
            "evidence types (timing, content, messaging).</p>" + graph_svg(state)]
    flagged = [al for al in an.alerts if al.severity in ("medium", "high")]
    body.append("<h2>Sample flagged cases</h2>")
    for al in flagged[:6]:
        c = case_for(al, an, state["by_agent"], roles)
        ev = "".join(f"<li><code>{esc(s)}</code> {esc(e['ts'])} {esc(e['kind'])} &rarr; {esc(e['target'])} "
                     f"({esc(e['status'])}) {esc(e['text'])}</li>" for s, evs in c["sample_events"].items() for e in evs[:3])
        gt = (" Generator ground truth: " + esc(", ".join(f"{k}={v}" for k, v in c["generator_ground_truth"].items()))
              if "generator_ground_truth" in c else "")
        body.append(f"<div class=card>{sev_badge(al.severity)} <strong>{esc(al.kind)}</strong> "
                    f"{esc(', '.join(al.subjects))}<br>{esc(al.summary)}<ul>{ev}</ul><small>{gt}</small></div>")
    return page("Dashboard", "".join(body))


def render_report_form(msg: str = "", cls: str = "", form=None) -> bytes:
    f = form or {}
    cats = [("unauthorized_access", "Unauthorized access attempts"), ("coordination", "Coordinated or colluding agents"),
            ("injection_misuse", "Prompt injection or tool misuse"), ("other", "Other")]
    opts = "".join(f'<option value="{k}"{" selected" if f.get("category") == k else ""}>{esc(v)}</option>' for k, v in cats)
    body = (f"<h2>Report suspicious AI activity</h2><p>This prototype stores reports <strong>locally only</strong>; nothing is "
            f"sent anywhere. Do not include passwords, keys, or personal data about people. Describe observable behavior, "
            f"not guesses about who is behind it.</p>"
            f"<p class={cls}>{esc(msg)}</p>"
            f'<form method="post" action="/report"><label>Agent reference (name, handle or id)</label>'
            f'<input name="agent_ref" maxlength="100" value="{esc(f.get("agent_ref", ""))}">'
            f"<label>Category</label><select name=category>{opts}</select>"
            f'<label>What did you observe? (20 to 2000 characters)</label><textarea name="description" rows="6">{esc(f.get("description", ""))}</textarea>'
            f'<label>Evidence link (optional, http or https)</label><input name="evidence_url" value="{esc(f.get("evidence_url", ""))}">'
            f"<button type=submit>Submit report</button></form>")
    return page("Report", body)


def md_to_html(md: str) -> str:
    out, in_ul = [], False
    for line in md.splitlines():
        s = line.rstrip()
        if s.startswith("- "):
            if not in_ul:
                out.append("<ul>")
                in_ul = True
            out.append(f"<li>{esc(s[2:])}</li>")
            continue
        if in_ul:
            out.append("</ul>")
            in_ul = False
        m = re.match(r"^(#{1,3}) (.*)", s)
        if m:
            n = len(m.group(1)) + 1
            out.append(f"<h{n}>{esc(m.group(2))}</h{n}>")
        elif s:
            out.append(f"<p>{esc(s)}</p>")
    if in_ul:
        out.append("</ul>")
    return "\n".join(out)


def make_handler(state: Dict):
    class H(BaseHTTPRequestHandler):
        def log_message(self, fmt, *args):  # keep test/CLI output quiet
            pass

        def _send(self, code: int, body: bytes, ctype: str = "text/html; charset=utf-8"):
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(body)))
            self.send_header("X-Content-Type-Options", "nosniff")
            self.send_header("Content-Security-Policy", "default-src 'none'; style-src 'unsafe-inline'; form-action 'self'")
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(body)

        def _json(self, obj):
            self._send(200, json.dumps(obj, indent=2, default=str).encode(), "application/json")

        def do_GET(self):
            path = urlparse(self.path).path
            an = state["analysis"]
            if path == "/":
                self._send(200, render_dashboard(state))
            elif path == "/api/alerts":
                self._json([r["alert"] for r in state["log"].read()])
            elif path == "/api/cases":
                self._json([case_for(a, an, state["by_agent"], state.get("roles")) for a in an.alerts
                            if a.severity in ("medium", "high")])
            elif path == "/api/verify":
                self._json({"intact": state["log"].verify() is None})
            elif path == "/report":
                self._send(200, render_report_form())
            elif path == "/resources":
                names = sorted(f for f in os.listdir(state["docs_dir"]) if f.endswith(".md"))
                links = "".join(f'<li><a href="/resources/{esc(n)}">{esc(n)}</a></li>' for n in names)
                self._send(200, page("Resources", f"<h2>Developer resources</h2><ul>{links}</ul>"))
            elif path.startswith("/resources/"):
                name = path[len("/resources/"):]
                if not re.fullmatch(r"[A-Za-z0-9_\-]+\.md", name) or not os.path.exists(os.path.join(state["docs_dir"], name)):
                    self._send(404, page("Not found", "<p>Not found.</p>"))
                    return
                with open(os.path.join(state["docs_dir"], name), encoding="utf-8") as fh:
                    self._send(200, page(name, md_to_html(fh.read())))
            else:
                self._send(404, page("Not found", "<p>Not found.</p>"))

        def do_POST(self):
            if urlparse(self.path).path != "/report":
                self._send(404, page("Not found", "<p>Not found.</p>"))
                return
            try:
                n = int(self.headers.get("Content-Length", "0"))
            except ValueError:
                n = -1
            if n < 0 or n > MAX_BODY:
                self._send(413, page("Too large", "<p>Request too large.</p>"))
                return
            form = {k: v[0] for k, v in parse_qs(self.rfile.read(n).decode("utf-8", "replace")).items()}
            try:
                clean = validate_report(form)
            except ValueError as exc:
                self._send(400, render_report_form(str(exc), "err", form))
                return
            rec = store_report(clean, state["reports_path"])
            self._send(200, render_report_form(f"Thank you. Stored locally as {rec['report_id']} (unreviewed).", "ok"))
    return H


def make_server(state: Dict, host: str = "127.0.0.1", port: int = 8765) -> ThreadingHTTPServer:
    return ThreadingHTTPServer((host, port), make_handler(state))


def serve_forever_in_thread(server: ThreadingHTTPServer) -> threading.Thread:
    t = threading.Thread(target=server.serve_forever, daemon=True)
    t.start()
    return t
